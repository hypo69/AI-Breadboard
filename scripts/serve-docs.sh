#!/bin/bash

# ============================================================================
# Скрипт для запуска локального HTTP-сервера с документацией
# ============================================================================
#
# Этот скрипт:
# 1. Проверяет наличие собранной документации в docs/ru/_build/html
# 2. Если документация не собрана, запускает build-docs.sh
# 3. Запускает простой HTTP-сервер на порту 8000
# 4. Выводит URL для доступа и инструкции по остановке
#
# Использование: ./scripts/serve-docs.sh
# ============================================================================

set -e

# Цвета для вывода
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

# Пути
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
DOCS_BUILD_DIR="$PROJECT_ROOT/docs/ru/_build/html"
BUILD_SCRIPT="$SCRIPT_DIR/build-docs.sh"

echo -e "${BLUE}╔═════════════════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║         Запуск локального сервера документации              ║${NC}"
echo -e "${BLUE}╚═════════════════════════════════════════════════════════════╝${NC}"
echo ""

# Проверка наличия собранной документации
if [ ! -d "$DOCS_BUILD_DIR" ]; then
    echo -e "${YELLOW}⚠️  Собранная документация не найдена в:${NC}"
    echo "   $DOCS_BUILD_DIR"
    echo ""
    echo -e "${YELLOW}🔨 Запуск сборки документации...${NC}"
    echo ""
    
    # Проверка наличия скрипта сборки
    if [ ! -f "$BUILD_SCRIPT" ]; then
        echo -e "${RED}❌ Ошибка: Скрипт $BUILD_SCRIPT не найден${NC}"
        exit 1
    fi
    
    # Запуск сборки
    bash "$BUILD_SCRIPT"
    
    echo ""
fi

# Проверка что документация теперь существует
if [ ! -d "$DOCS_BUILD_DIR" ]; then
    echo -e "${RED}❌ Ошибка: Не удалось собрать документацию${NC}"
    exit 1
fi

# Проверка что в директории есть индекс
if [ ! -f "$DOCS_BUILD_DIR/index.html" ]; then
    echo -e "${RED}❌ Ошибка: Файл index.html не найден в $DOCS_BUILD_DIR${NC}"
    exit 1
fi

echo -e "${GREEN}✓ Документация готова${NC}"
echo ""

# Переход в директорию с документацией
cd "$DOCS_BUILD_DIR"

echo -e "${GREEN}✓ Запуск HTTP-сервера...${NC}"
echo ""
echo -e "${BLUE}╔═════════════════════════════════════════════════════════════╗${NC}"
echo -e "${BLUE}║                   СЕРВЕР ЗАПУЩЕН                           ║${NC}"
echo -e "${BLUE}╚═════════════════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "📖  Адрес доступа: ${GREEN}http://localhost:8000${NC}"
echo ""
echo -e "🌐  Открыть в браузере: ${GREEN}http://localhost:8000/index.html${NC}"
echo ""
echo -e "📁  Документация находится в: ${YELLOW}$DOCS_BUILD_DIR${NC}"
echo ""
echo -e "${YELLOW}─────────────────────────────────────────────────────────────${NC}"
echo -e "${YELLOW}Для остановки сервера нажмите: Ctrl+C${NC}"
echo -e "${YELLOW}─────────────────────────────────────────────────────────────${NC}"
echo ""

# Запуск HTTP-сервера на порту 8000
python -m http.server 8000

# Информация при остановке сервера
echo ""
echo -e "${YELLOW}⏹️  Сервер остановлен${NC}"
